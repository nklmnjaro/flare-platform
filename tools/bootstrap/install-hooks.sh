#!/bin/bash -p
# Generated hooks intentionally retain literal shell variables.
# shellcheck disable=SC2016
set -euo pipefail

INSTALL_HOOKS_AMBIENT_GIT_SELECTORS=false
if [[ -v GIT_DIR || -v GIT_COMMON_DIR || -v GIT_WORK_TREE ]]; then
  INSTALL_HOOKS_AMBIENT_GIT_SELECTORS=true
fi
INSTALL_HOOKS_SOURCE_DIR="${BASH_SOURCE[0]%/*}"
[[ "${INSTALL_HOOKS_SOURCE_DIR}" != "${BASH_SOURCE[0]}" ]] ||
  INSTALL_HOOKS_SOURCE_DIR=.
builtin source "${INSTALL_HOOKS_SOURCE_DIR}/../common/env.sh"
builtin source "${PLATFORM_ROOT}/tools/common/tooling.sh"
unset INSTALL_HOOKS_SOURCE_DIR

readonly -a HOOK_TYPES=(pre-commit commit-msg)
HOOK_WORK_DIR=""
HOOK_DIRECTORY=""
HOOK_ROLLBACK_FAILED=false
declare -a HOOK_PATHS=() HOOK_BACKUPS=() HOOK_CANDIDATES=() HOOK_PUBLISHED=()

hook_failure() {
  printf 'FAIL  hooks         %s\n' "$1" >&2
  return 1
}

resolve_hook_directory() {
  local common_directory configured_directory
  common_directory="$(run_host_command git -C "${PLATFORM_ROOT}" \
    rev-parse --git-common-dir)" || return
  [[ "${common_directory}" == /* ]] ||
    common_directory="${PLATFORM_ROOT}/${common_directory}"
  configured_directory="$(run_host_command git -C "${PLATFORM_ROOT}" \
    rev-parse --git-path hooks)" || return
  [[ "${configured_directory}" == /* ]] ||
    configured_directory="${PLATFORM_ROOT}/${configured_directory}"
  if [[ ! -d "${common_directory}" || -L "${common_directory}" ||
    ! -d "${configured_directory}" || -L "${configured_directory}" ]]; then
    hook_failure 'Git hook directory is unsafe'
    return
  fi
  common_directory="$(builtin cd -P -- "${common_directory}" &&
    builtin pwd -P)" || return
  configured_directory="$(builtin cd -P -- "${configured_directory}" &&
    builtin pwd -P)" || return
  if [[ "${configured_directory}" != "${common_directory}/hooks" ||
    -L "${common_directory}/hooks" ]]; then
    hook_failure 'Git hook directory is outside canonical git common directory'
    return
  fi
  HOOK_DIRECTORY="${configured_directory}"
}

prepare_hook_transaction() {
  local index hook_type hook_path parent
  ensure_state_directory "" || {
    hook_failure 'project state root is unsafe'
    return
  }
  resolve_hook_directory || return
  HOOK_WORK_DIR="$(run_host_command mktemp -d \
    "${PLATFORM_STATE_DIR}/.hooks-install.XXXXXXXX")" || return
  run_host_command git init --quiet --bare "${HOOK_WORK_DIR}/git" || return
  for index in "${!HOOK_TYPES[@]}"; do
    hook_type="${HOOK_TYPES[${index}]}"
    hook_path="${HOOK_DIRECTORY}/${hook_type}"
    parent="${hook_path%/*}"
    if [[ ! -d "${parent}" || -L "${parent}" || -L "${hook_path}" ||
      (-e "${hook_path}" && ! -f "${hook_path}") ]]; then
      hook_failure "${hook_type} hook path is unsafe"
      return
    fi
    HOOK_PATHS[index]="${hook_path}"
    HOOK_PUBLISHED[index]=false
    if [[ -f "${hook_path}" ]]; then
      if [[ "$(run_host_command grep -Fxc \
        '# File generated by prek: https://github.com/j178/prek' \
        "${hook_path}" || true)" != 1 ]]; then
        hook_failure "refusing to replace unmanaged ${hook_type} hook"
        return
      fi
      HOOK_BACKUPS[index]="${HOOK_WORK_DIR}/${hook_type}.before"
      run_host_command cp -pT -- "${hook_path}" \
        "${HOOK_BACKUPS[${index}]}" || return
    else
      HOOK_BACKUPS[index]=""
    fi
  done
}

validate_generated_hook() {
  local hook_type="$1" generated="$2"
  if [[ ! -f "${generated}" || -L "${generated}" ]] ||
    [[ "$(run_host_command grep -Fxc \
      '# File generated by prek: https://github.com/j178/prek' \
      "${generated}" || true)" != 1 ]] ||
    ! run_host_command grep -Fq -- \
      "--script-version 4 --hook-type=${hook_type} -- \"\$@\"" \
      "${generated}"; then
    hook_failure "generated ${hook_type} hook shape is untrusted"
    return 1
  fi
}

write_hardened_hook() {
  local index="$1" hook_type generated candidate status=0
  hook_type="${HOOK_TYPES[${index}]}"
  generated="${HOOK_WORK_DIR}/git/hooks/${hook_type}"
  if [[ "${PLATFORM_TEST_FAIL_HOOK_HARDEN:-}" == "${hook_type}" ]]; then
    hook_failure "forced ${hook_type} hardening failure"
    return
  fi
  validate_generated_hook "${hook_type}" "${generated}" || return
  candidate="$(run_host_command mktemp \
    "${HOOK_PATHS[${index}]}.managed.XXXXXXXX")" || return
  HOOK_CANDIDATES[index]="${candidate}"
  {
    printf '#!/bin/bash -p\n'
    printf '# File generated by prek: https://github.com/j178/prek\n'
    printf '# Hardened and published transactionally by flare-platform.\n'
    printf 'set -euo pipefail\n\n'
    printf 'readonly PLATFORM_HOOK_ROOT=%q\n' "${PLATFORM_ROOT}"
    printf 'readonly PLATFORM_HOOK_DIR=%q\n' "${HOOK_DIRECTORY}"
    printf 'unset GIT_DIR GIT_COMMON_DIR GIT_WORK_TREE\n'
    printf 'builtin cd -P -- "${PLATFORM_HOOK_ROOT}"\n'
    printf 'builtin source "${PLATFORM_HOOK_ROOT}/tools/common/env.sh"\n'
    printf 'builtin source "${PLATFORM_ROOT}/tools/common/tooling.sh"\n'
    printf 'run_managed_tool prek hook-impl --hook-dir "${PLATFORM_HOOK_DIR}" \\\n'
    printf '  --script-version 4 --hook-type=%q -- "$@"\n' "${hook_type}"
  } >"${candidate}" || status=$?
  if ((status == 0)); then
    run_host_command chmod 0755 -- "${candidate}" || status=$?
  fi
  return "${status}"
}

restore_published_hooks() {
  local index hook_path backup restore status=0
  for index in "${!HOOK_TYPES[@]}"; do
    [[ "${HOOK_PUBLISHED[${index}]:-false}" == true ]] || continue
    hook_path="${HOOK_PATHS[${index}]}"
    backup="${HOOK_BACKUPS[${index}]}"
    if [[ "${PLATFORM_TEST_FAIL_HOOK_RESTORE:-}" == "${HOOK_TYPES[${index}]}" ]]; then
      status=74
      continue
    fi
    if [[ -n "${backup}" ]]; then
      restore="$(run_host_command mktemp \
        "${hook_path}.restore.XXXXXXXX")" || {
        status=74
        continue
      }
      if ! run_host_command cp -pT -- "${backup}" "${restore}" ||
        ! run_host_command mv -fT -- "${restore}" "${hook_path}"; then
        run_host_command rm -f -- "${restore}" || true
        status=74
      else
        HOOK_PUBLISHED[index]=false
      fi
    elif run_host_command rm -f -- "${hook_path}"; then
      HOOK_PUBLISHED[index]=false
    else
      status=74
    fi
  done
  return "${status}"
}

publish_hardened_hooks() {
  local index hook_type restore_status
  for index in "${!HOOK_TYPES[@]}"; do
    hook_type="${HOOK_TYPES[${index}]}"
    if [[ "${PLATFORM_TEST_FAIL_HOOK_PUBLISH:-}" == "${hook_type}" ]]; then
      restore_status=0
      restore_published_hooks || restore_status=$?
      if ((restore_status != 0)); then
        HOOK_ROLLBACK_FAILED=true
        hook_failure \
          "unable to restore hooks after forced publication failure; recovery data retained at ${HOOK_WORK_DIR}" || true
        return 74
      fi
      hook_failure "forced ${hook_type} publication failure"
      return
    fi
    if ! run_host_command mv -fT -- "${HOOK_CANDIDATES[${index}]}" \
      "${HOOK_PATHS[${index}]}"; then
      restore_status=0
      restore_published_hooks || restore_status=$?
      if ((restore_status != 0)); then
        HOOK_ROLLBACK_FAILED=true
        hook_failure \
          "unable to restore hooks after publication failure; recovery data retained at ${HOOK_WORK_DIR}" || true
        return 74
      fi
      return 1
    fi
    HOOK_CANDIDATES[index]=""
    HOOK_PUBLISHED[index]=true
  done
}

cleanup_hook_transaction() {
  local candidate
  for candidate in "${HOOK_CANDIDATES[@]:-}"; do
    [[ -z "${candidate}" ]] || run_host_command rm -f -- "${candidate}" || true
  done
  [[ "${HOOK_ROLLBACK_FAILED}" == false ]] || return 0
  if [[ -n "${HOOK_WORK_DIR}" ]]; then
    case "${HOOK_WORK_DIR}" in
      "${PLATFORM_STATE_DIR}"/.hooks-install.*)
        run_host_command rm -rf -- "${HOOK_WORK_DIR}"
        ;;
      *) hook_failure 'refusing unsafe hook transaction cleanup' ;;
    esac
  fi
}

validate_test_controls() {
  case "${PLATFORM_TEST_FAIL_HOOK_HARDEN:-}" in
    '' | pre-commit | commit-msg) ;;
    *)
      hook_failure 'invalid hook hardening fixture request'
      return
      ;;
  esac
  case "${PLATFORM_TEST_FAIL_HOOK_PUBLISH:-}" in
    '' | pre-commit | commit-msg) ;;
    *)
      hook_failure 'invalid hook publication fixture request'
      return
      ;;
  esac
  case "${PLATFORM_TEST_FAIL_HOOK_RESTORE:-}" in
    '' | pre-commit | commit-msg) ;;
    *)
      hook_failure 'invalid hook restore fixture request'
      return
      ;;
  esac
}

main() {
  local index
  validate_test_controls || return
  if [[ "${INSTALL_HOOKS_AMBIENT_GIT_SELECTORS}" == true ]]; then
    hook_failure 'ambient Git repository selectors are not allowed'
    return
  fi
  require_tool prek
  trap cleanup_hook_transaction EXIT
  prepare_hook_transaction
  run_managed_tool prek install --git-dir "${HOOK_WORK_DIR}/git" \
    --hook-type pre-commit --hook-type commit-msg
  for index in "${!HOOK_TYPES[@]}"; do
    write_hardened_hook "${index}"
  done
  publish_hardened_hooks
  trap - EXIT
  cleanup_hook_transaction
  printf 'PASS  hooks         pre-commit and commit-msg hooks installed\n'
}

main "$@"
